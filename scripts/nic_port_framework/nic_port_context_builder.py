#!/usr/bin/env python3
"""
nic_port_context_builder.py

Compiler-database-driven context builder for production NIC-driver porting work.

Purpose
-------
Create a reproducible, machine-readable source knowledge base and a set of
LLM-ready engineering prompts for re-hosting a C driver from one OS to another
(e.g. Linux -> FreeBSD).

The tool does NOT attempt a mechanical source translation.  It extracts the
facts needed for semantic porting reviews:

  * authoritative translation units from compile_commands.json
  * source/build baseline and file hashes
  * functions, bodies, declarations, callers and callees
  * callback/function-pointer references
  * external/OS API calls and semantic categories
  * structure/field definitions and field access summaries
  * local macro definitions and macros referenced by functions
  * includes, active -D compile definitions, and per-TU command lines
  * subsystem heuristics and portability-risk hints
  * DOT call/dependency graphs
  * per-method, per-file, per-subsystem, architecture and final-design prompts
  * optional dedicated LibTooling extraction backend for very large projects
  * compiler-derived macro expansion/#if provenance when LibTooling is enabled
  * function-pointer binding/candidate analysis and alias-aware field paths
  * stable symbol IDs and local semantic fingerprints for delta analysis

It intentionally keeps extraction deterministic and LLM-independent.  The LLM
is used only after the evidence package has been built.

Requirements
------------
  * Python 3.10+
  * clang in PATH (or --clang /path/to/clang)
  * compile_commands.json generated by the real build whenever possible

For Linux kernel/out-of-tree module work, prefer the kernel's generated compile
commands.  A source scan fallback is available, but it is explicitly marked
non-authoritative.

Example
-------
  python3 nic_port_context_builder.py \
      --source /work/ethernet-linux-idpf/idpf/src \
      --compile-commands /work/linux/compile_commands.json \
      --project-name idpf \
      --source-os Linux \
      --target-os FreeBSD \
      --out /work/idpf-port-analysis

Then review:
  /work/idpf-port-analysis/prompts/00_architecture_review.md
  /work/idpf-port-analysis/prompts/methods/*.md
  /work/idpf-port-analysis/prompts/files/*.md
  /work/idpf-port-analysis/prompts/subsystems/*.md
  /work/idpf-port-analysis/prompts/99_final_port_design.md

Exit status is non-zero if strict extraction failures occur.
"""

