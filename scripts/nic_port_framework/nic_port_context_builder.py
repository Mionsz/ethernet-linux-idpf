def norm(path: str | Path) -> str:
    return str(Path(path).expanduser().resolve())


def rel(path: str | Path, root: Path) -> str:
    try:
        return str(Path(path).resolve().relative_to(root.resolve()))
    except Exception:
        return str(Path(path))


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8", errors="replace")).hexdigest()


def canonical_hash(obj: Any) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")).hexdigest()


def json_write(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2, sort_keys=True, ensure_ascii=False)
        f.write("\n")
    tmp.replace(path)


def jsonl_write(path: Path, rows: Iterable[Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8") as f:
        for row in rows:
            if dataclasses.is_dataclass(row) and not isinstance(row, type):
                row = asdict(cast(Any, row))
            f.write(json.dumps(row, sort_keys=True, ensure_ascii=False) + "\n")
    tmp.replace(path)


def text_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def run_git(source: Path, *args: str) -> str | None:
    try:
        cp = subprocess.run(
            ["git", "-C", str(source), *args],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            timeout=10,
            check=True,
        )
        return cp.stdout.strip()
    except Exception:
        return None


def source_manifest(source: Path, ignore_dirs: set[str]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for p in sorted(source.rglob("*")):
        if not p.is_file() or p.suffix.lower() not in SOURCE_EXTS:
            continue
        if any(part in ignore_dirs for part in p.relative_to(source).parts):
            continue
        try:
            st = p.stat()
            rows.append({
                "path": rel(p, source),
                "bytes": st.st_size,
                "sha256": sha256_file(p),
            })
        except OSError as exc:
            rows.append({"path": rel(p, source), "error": str(exc)})
    return rows


def split_compile_command(entry: dict[str, Any]) -> list[str]:
    if isinstance(entry.get("arguments"), list):
        return [str(x) for x in entry["arguments"]]
    if entry.get("command"):
        return shlex.split(entry["command"])
    raise ExtractionError("compile_commands entry has neither 'arguments' nor 'command'")


def extract_defines(args: list[str]) -> list[str]:
    out: list[str] = []
    i = 0
    while i < len(args):
        a = args[i]
        if a == "-D" and i + 1 < len(args):
            out.append(args[i + 1])
            i += 2
            continue
        if a.startswith("-D") and len(a) > 2:
            out.append(a[2:])
        i += 1
    return sorted(set(out))



