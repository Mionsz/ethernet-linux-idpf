def _runtime_get(path: str, default: Any = None) -> Any:
    cur: Any = EXTRACTION_RUNTIME
    for part in path.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return default
        cur = cur[part]
    return cur


def _libtooling_row_to_result(cu0: CompileUnit, row: dict[str, Any], source: Path) -> TUResult:
    tu_rel = str(row.get("tu_file") or rel(cu0.file, source))
    funcs: list[FunctionRecord] = []
    for f in row.get("functions") or []:
        calls = [_call_from_obj(x) for x in (f.get("calls_raw") or []) if isinstance(x, dict)]
        accesses = [_field_access_from_obj(x) for x in (f.get("field_accesses") or []) if isinstance(x, dict)]
        fr = FunctionRecord(
            key=str(f.get("key") or f"{tu_rel}:{f.get('line_start') or 0}:{f.get('name') or '<anonymous>'}"),
            name=str(f.get("name") or "<anonymous>"),
            file=str(f.get("file") or tu_rel),
            line_start=int(f.get("line_start") or 0),
            line_end=int(f.get("line_end") or f.get("line_start") or 0),
            storage=f.get("storage"), return_type=f.get("return_type"),
            signature=str(f.get("signature") or ""), body=str(f.get("body") or ""),
            full_source=str(f.get("full_source") or ""), tu_file=tu_rel, defines=cu0.defines,
            calls_raw=calls, field_accesses=accesses,
            callback_references=list(f.get("callback_references") or []),
            stable_id=str(f.get("stable_id") or f"FN::{f.get('file') or tu_rel}::{f.get('name') or '<anonymous>'}"),
            alias_relations=list(f.get("alias_relations") or []),
            function_pointer_bindings=list(f.get("function_pointer_bindings") or []),
        )
        fr.subsystems = assign_subsystems(fr.name, fr.file, fr.body)
        funcs.append(fr)
    structs = [StructRecord(
        key=str(x.get("key") or ""), name=str(x.get("name") or "<anonymous>"),
        kind=str(x.get("kind") or "record"), file=str(x.get("file") or tu_rel),
        line=int(x.get("line") or 0), fields=list(x.get("fields") or []), source=str(x.get("source") or "")
    ) for x in (row.get("structs") or [])]
    enums = [EnumRecord(
        key=str(x.get("key") or ""), name=str(x.get("name") or "<anonymous>"),
        file=str(x.get("file") or tu_rel), line=int(x.get("line") or 0),
        values=list(x.get("values") or []), source=str(x.get("source") or "")
    ) for x in (row.get("enums") or [])]
    pp_events = []
    for event in (row.get("pp_events") or []):
        if isinstance(event, dict):
            event = dict(event)
            event.setdefault("translation_unit", tu_rel)
            pp_events.append(event)
    fp_bindings = []
    for binding in (row.get("function_pointer_bindings") or []):
        if isinstance(binding, dict):
            binding = dict(binding)
            binding.setdefault("translation_unit", tu_rel)
            fp_bindings.append(binding)
    return TUResult(
        tu=cu0, functions=funcs, structs=structs, enums=enums,
        callback_refs=list(row.get("callback_refs") or []),
        errors=list(row.get("errors") or []),
        pp_events=pp_events,
        function_pointer_bindings=fp_bindings,
        backend="libtooling",
    )


def _proc_meminfo_kb() -> dict[str, int | None]:
    """Best-effort Linux memory telemetry; empty on non-/proc platforms."""
    out: dict[str, int | None] = {"mem_available_kb": None, "parent_rss_kb": None, "parent_hwm_kb": None}
    try:
        for line in Path("/proc/meminfo").read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith("MemAvailable:"):
                out["mem_available_kb"] = int(line.split()[1])
                break
    except Exception:
        pass
    try:
        for line in Path("/proc/self/status").read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith("VmRSS:"):
                out["parent_rss_kb"] = int(line.split()[1])
            elif line.startswith("VmHWM:"):
                out["parent_hwm_kb"] = int(line.split()[1])
    except Exception:
        pass
    return out




def _atomic_json_write(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + f".tmp.{os.getpid()}")
    tmp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, path)


