def write_graphs(out: Path, functions: list[FunctionRecord]) -> None:
    fn_by_key = {f.key: f for f in functions}
    lines = ["digraph callgraph {", '  rankdir="LR";', '  node [shape=box,fontname="monospace",fontsize=9];']
    for fn in functions:
        node = "n" + hashlib.sha1(fn.key.encode()).hexdigest()[:12]
        label = f"{fn.name}\\n{fn.file}:{fn.line_start}\\n{fn.portability_score}"
        lines.append(f'  {node} [label="{label}"];')
    for fn in functions:
        src = "n" + hashlib.sha1(fn.key.encode()).hexdigest()[:12]
        for ck in fn.calls_internal:
            if ck in fn_by_key:
                dst = "n" + hashlib.sha1(ck.encode()).hexdigest()[:12]
                lines.append(f"  {src} -> {dst};")
    lines.append("}")
    text_write(out / "graphs" / "callgraph.dot", "\n".join(lines) + "\n")

    # Function -> semantic OS service graph.
    lines = ["digraph osdeps {", '  rankdir="LR";', '  node [fontname="monospace",fontsize=9];']
    services = sorted(set(cat for f in functions for c in f.calls_external for cat in c.get("categories", [])))
    for s in services:
        sid = "s" + hashlib.sha1(s.encode()).hexdigest()[:12]
        lines.append(f'  {sid} [shape=ellipse,label="{s}"];')
    for fn in functions:
        fid = "n" + hashlib.sha1(fn.key.encode()).hexdigest()[:12]
        lines.append(f'  {fid} [shape=box,label="{fn.name}"];')
        cats = sorted(set(cat for c in fn.calls_external for cat in c.get("categories", [])))
        for s in cats:
            sid = "s" + hashlib.sha1(s.encode()).hexdigest()[:12]
            lines.append(f"  {fid} -> {sid};")
    lines.append("}")
    text_write(out / "graphs" / "os_service_dependencies.dot", "\n".join(lines) + "\n")



def build_context_packages(
    out: Path,
    source: Path,
    functions: list[FunctionRecord],
    structs: list[StructRecord],
    macros: list[MacroRecord],
    project_name: str,
    source_os: str,
    target_os: str,
    max_context_chars: int,
    max_file_chars: int,
) -> None:
    fn_by_key = {f.key: f for f in functions}
    macros_by = macro_lookup(macros)

    # Method contexts + prompts.
    for fn in functions:
        slug = safe_slug(fn.key)
        ctx = compact_fn(fn)
        ctx["body"] = fn.body
        ctx["full_source"] = fn.full_source
        ctx["relevant_structs"] = [asdict(s) for s in relevant_structs(fn, structs)]
        ctx["macro_definitions"] = {
            name: [asdict(m) for m in macros_by.get(name, [])[:4]]
            for name in fn.macros
        }
        ctx["caller_context"] = [compact_fn(fn_by_key[k]) for k in fn.callers if k in fn_by_key]
        ctx["callee_context"] = [compact_fn(fn_by_key[k]) for k in fn.calls_internal if k in fn_by_key]
        json_write(out / "contexts" / "methods" / f"{slug}.json", ctx)
        text_write(
            out / "prompts" / "methods" / f"{slug}.md",
            render_method_prompt(fn, source, fn_by_key, structs, macros_by, source_os, target_os, project_name, max_context_chars),
        )

    # File contexts + prompts.
    by_file: dict[str, list[FunctionRecord]] = defaultdict(list)
    for fn in functions:
        by_file[fn.file].append(fn)
    for file, fns in sorted(by_file.items()):
        slug = safe_slug(file)
        json_write(out / "contexts" / "files" / f"{slug}.json", {
            "file": file,
            "functions": [compact_fn(x) for x in sorted(fns, key=lambda z: z.line_start)],
        })
        text_write(
            out / "prompts" / "files" / f"{slug}.md",
            render_file_prompt(file, sorted(fns, key=lambda z: z.line_start), source, project_name, source_os, target_os, max_file_chars),
        )

    # Subsystem contexts + prompts.
    by_sub: dict[str, list[FunctionRecord]] = defaultdict(list)
    for fn in functions:
        for sub in fn.subsystems:
            by_sub[sub].append(fn)
    for sub, fns in sorted(by_sub.items()):
        json_write(out / "contexts" / "subsystems" / f"{safe_slug(sub)}.json", {
            "subsystem": sub,
            "functions": [compact_fn(x) for x in sorted(fns, key=lambda z: (z.file, z.line_start))],
        })
        text_write(
            out / "prompts" / "subsystems" / f"{safe_slug(sub)}.md",
            render_subsystem_prompt(sub, fns, project_name, source_os, target_os),
        )


