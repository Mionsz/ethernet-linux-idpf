def apply_manifest_configuration(manifest: dict[str, Any]) -> tuple[set[str], dict[str, Any]]:
    """Load all semantic/pattern policy from manifest-referenced files.

    Multiple semantic rule files are intentionally additive for API patterns,
    subsystem patterns and ignore directories; target hints/risk weights are
    overlaid by later files.  This is the supported extension mechanism for
    LINUX_API_PATTERNS, FREEBSD_TARGET_HINTS, SUBSYSTEM_PATTERNS,
    RISK_WEIGHTS and DEFAULT_IGNORE_DIRS.
    """
    global SOURCE_EXTS, LINUX_API_PATTERNS, FREEBSD_TARGET_HINTS, SUBSYSTEM_PATTERNS
    global RISK_WEIGHTS, DEFAULT_IGNORE_DIRS, GENERATED_TU_PATTERNS
    global EXTERNAL_UNCLASSIFIED_TARGET_HINT, TEMPLATES, API_CATALOG, LINUX_SPECIFIC_RULES
    global INCLUDE_CLASSIFICATION, PORTABILITY_SCORING, TOOLING_NORMALIZATION, REPORT_LAYOUT, CONTEXT_LAYOUT, OUTPUT_CATALOG, FRAMEWORK_MODEL, EXTRACTION_RUNTIME
    rules = load_semantic_rules(manifest)
    API_CATALOG = load_api_catalog(manifest)
    LINUX_SPECIFIC_RULES = load_linux_specific_rules(manifest)
    INCLUDE_CLASSIFICATION = load_include_classification(manifest)
    PORTABILITY_SCORING = load_portability_scoring(manifest)
    TOOLING_NORMALIZATION = load_tooling_normalization(manifest)
    REPORT_LAYOUT = load_report_layout(manifest)
    CONTEXT_LAYOUT = load_context_layout(manifest)
    OUTPUT_CATALOG = load_output_catalog(manifest)
    FRAMEWORK_MODEL = load_framework_model(manifest)
    EXTRACTION_RUNTIME = load_extraction_runtime(manifest)
    catalog_conflicts = API_CATALOG.get("_conflicts") or []
    conflict_policy = str((FRAMEWORK_MODEL.get("configuration_integrity") or {}).get("api_catalog_conflict_policy") or "error")
    if catalog_conflicts and conflict_policy == "error":
        raise ManifestError(f"API catalogue has {len(catalog_conflicts)} conflicting exact-symbol redefinition(s); resolve or change configuration_integrity.api_catalog_conflict_policy")
    SOURCE_EXTS = set(rules.get("source_extensions") or [])
    if not SOURCE_EXTS:
        raise ManifestError("semantic rules must define source_extensions")
    LINUX_API_PATTERNS = {str(k): [str(x) for x in v] for k, v in (rules.get("linux_api_patterns") or {}).items()}
    FREEBSD_TARGET_HINTS = {str(k): str(v) for k, v in (rules.get("freebsd_target_hints") or {}).items()}
    SUBSYSTEM_PATTERNS = [(str(k), [str(x) for x in v]) for k, v in (rules.get("subsystem_patterns") or {}).items()]
    RISK_WEIGHTS = {str(k): int(v) for k, v in (rules.get("risk_weights") or {}).items()}
    DEFAULT_IGNORE_DIRS = set(str(x) for x in (rules.get("ignore_dirs") or []))
    GENERATED_TU_PATTERNS = [str(x) for x in (rules.get("generated_translation_unit_patterns") or [])]
    EXTERNAL_UNCLASSIFIED_TARGET_HINT = str(rules.get("external_unclassified_target_hint") or "")
    TEMPLATES = load_template_index(manifest)
    return set(DEFAULT_IGNORE_DIRS), rules


def build_doc_search_queue(functions: list[FunctionRecord], source_os: str, target_os: str) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str]] = set()
    eligible = set(str(x) for x in (PORTABILITY_SCORING.get("documentation_detection_sources") or []))
    for fn in functions:
        candidates: list[dict[str, Any]] = []
        for c in fn.calls_external:
            candidates.append({"symbol": c.get("name"), "categories": c.get("categories") or [], "detection_source": "ast_external_call"})
        for h in fn.catalog_api_hits:
            if str(h.get("detection_source")) not in eligible:
                continue
            candidates.append({"symbol": h.get("symbol"), "categories": [h.get("semantic_category")], "detection_source": h.get("detection_source")})
        for c in candidates:
            name = c.get("symbol") or "<unknown>"
            for cat in c.get("categories", []) or ["external_unclassified"]:
                if not cat:
                    continue
                key = (fn.key, str(name), str(cat))
                if key in seen:
                    continue
                seen.add(key)
                rows.append({
                    "function_key": fn.key,
                    "symbol": name,
                    "semantic_category": cat,
                    "detection_source": c.get("detection_source"),
                    "source_os": source_os,
                    "target_os": target_os,
                    "source_question": f"What are the authoritative {source_os} semantics, execution-context constraints, ownership/lifetime rules, error behavior and memory-order requirements of {name}?",
                    "target_question": f"Which native {target_os} facility should provide the semantic service '{cat}', and what lifecycle/concurrency differences prevent a mechanical mapping?",
                    "target_research_hint": FREEBSD_TARGET_HINTS.get(cat, EXTERNAL_UNCLASSIFIED_TARGET_HINT),
                    "status": "NEEDED",
                    "confidence": "C0",
                    "evidence": []
                })
    return rows


def file_preamble(source: Path, fn: FunctionRecord, max_lines: int | None = None, max_chars: int | None = None) -> str:
    p = source / fn.file
    try:
        lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    if max_lines is None:
        max_lines = int(CONTEXT_LAYOUT["file_preamble_max_lines"])
    if max_chars is None:
        max_chars = int(CONTEXT_LAYOUT["file_preamble_max_chars"])
    end = min(max(0, fn.line_start - 1), max_lines)
    return clip("\n".join(lines[:end]), max_chars)


def render_related_sources(items: list[FunctionRecord], max_items: int, per_item_chars: int, title: str) -> str:
    parts: list[str] = []
    for x in items[:max_items]:
        parts.append(f"### {x.key}\n\n{markdown_code(clip(x.full_source, per_item_chars), 'c')}")
    return "\n\n".join(parts) if parts else f"No {title.lower()} detected."

def _workspace_rel(name: str, default: str) -> Path:
    value = _runtime_get(f"workspace.{name}", default)
    return Path(str(value or default))


def write_run_state(out: Path, *, run_id: str, status: str, phase: str,
                    message: str | None = None, extra: dict[str, Any] | None = None) -> Path:
    path = out / _workspace_rel("run_state_file", "manifest/run_state.json")
    previous = {}
    if path.is_file():
        try:
            previous = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            previous = {}
    payload = {
        "schema_version": "3.3",
        "run_id": run_id,
        "status": status,
        "phase": phase,
        "updated_utc": now_iso(),
        "started_utc": previous.get("started_utc") if previous.get("run_id") == run_id else now_iso(),
        "message": message,
    }
    if extra:
        payload.update(extra)
    json_write(path, payload)
    return path


def build_extraction_quality(compile_units: list[CompileUnit], results: list[TUResult], *, authoritative: bool) -> dict[str, Any]:
    cfg = dict(_runtime_get("quality_gate", {}) or {})
    total = len(compile_units)
    recovered = sum(1 for r in results if r.recovered and r.functions and not r.errors and not r.failure_class)
    success = sum(1 for r in results if (not r.recovered) and r.functions and not r.errors and not r.failure_class)
    failed_rows = [r for r in results if (not r.functions) or r.errors or r.failure_class]
    accounted = len(results)
    ratio = ((success + recovered) / total) if total else 0.0
    blockers: list[str] = []
    warnings: list[str] = []
    if bool(cfg.get("require_authoritative_compile_database", True)) and not authoritative:
        blockers.append("Compilation database is not authoritative.")
    if bool(cfg.get("require_all_translation_units_accounted", True)) and accounted != total:
        blockers.append(f"Only {accounted}/{total} translation units produced an extraction result.")
    max_failed = int(cfg.get("maximum_failed_translation_units", 0) or 0)
    if len(failed_rows) > max_failed:
        blockers.append(f"{len(failed_rows)} translation unit(s) failed/partial; allowed maximum is {max_failed}.")
    min_ratio = float(cfg.get("minimum_translation_unit_success_ratio", 1.0) or 0.0)
    if ratio < min_ratio:
        blockers.append(f"Translation-unit success ratio {ratio:.4f} is below required {min_ratio:.4f}.")
    if not bool(cfg.get("allow_recovered_translation_units", True)) and recovered:
        blockers.append(f"{recovered} translation unit(s) required fallback recovery, which policy disallows.")
    if bool(cfg.get("require_nonempty_function_set_for_source_translation_units", True)):
        empty = [r.tu.file for r in results if not r.functions]
        if empty:
            blockers.append(f"{len(empty)} source translation unit(s) produced no function definitions.")
    if bool(cfg.get("require_nonempty_local_function_set_for_source_translation_units", True)):
        local_empty = []
        for r in results:
            tu_rel = Path(r.tu.file).name if not r.tu.file else None
            # FunctionRecord.file is project-relative; compare by source basename as
            # a fallback because the quality function intentionally has no source-root argument.
            local_count = sum(1 for f in r.functions if Path(f.file).name == Path(r.tu.file).name)
            if local_count == 0:
                local_empty.append(r.tu.file)
        if local_empty:
            blockers.append(f"{len(local_empty)} source translation unit(s) produced no local source-file function definitions.")
    if recovered:
        warnings.append(f"{recovered} translation unit(s) were recovered by a fallback backend.")
    diagnostics = list(getattr(run_libtooling_extractor, "last_diagnostics", []) or [])
    cache_hits = sum(1 for d in diagnostics if d.get("cache_hit"))
    fresh = sum(1 for d in diagnostics if not d.get("cache_hit"))
    unclassified = sum(1 for r in failed_rows if not r.failure_class)
    max_unclassified = int(cfg.get("maximum_unclassified_failures", 0) or 0)
    if unclassified > max_unclassified:
        blockers.append(f"{unclassified} failed translation unit(s) have no failure_class; allowed maximum is {max_unclassified}.")
    return {
        "schema_version": "3.3",
        "generated_utc": now_iso(),
        "status": "FAIL" if blockers else "PASS",
        "authoritative_compile_database": authoritative,
        "translation_units_total": total,
        "translation_units_accounted": accounted,
        "translation_units_success": success,
        "translation_units_recovered": recovered,
        "translation_units_failed_or_partial": len(failed_rows),
        "translation_unit_success_ratio": round(ratio, 6),
        "translation_units_cache_hits": cache_hits,
        "translation_units_fresh_extractions": fresh,
        "deterministic_merge": True,
        "failed_translation_units": [{
            "translation_unit": r.tu.file,
            "backend": r.backend,
            "failure_class": r.failure_class,
            "errors": r.errors,
            "returncode": r.returncode,
            "signal": r.signal,
        } for r in failed_rows],
        "blockers": blockers,
        "warnings": warnings,
        "policy": cfg,
    }

def main(argv: list[str] | None = None) -> int:
    default_manifest = Path(__file__).resolve().parent / "config" / "default.manifest.json"
    ap = argparse.ArgumentParser(
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
        description="Build a deterministic source knowledge base from one manifest entrypoint.",
    )
    ap.add_argument("--manifest", default=str(default_manifest), help="Single input manifest entrypoint; includes may extend it")
    # Legacy/diagnostic overrides remain available but are deliberately optional.
    ap.add_argument("--source", help="Override manifest inputs.source_root")
    ap.add_argument("--compile-commands", help="Override manifest inputs.compile_commands")
    ap.add_argument("--out", help="Override manifest output.root")
    ap.add_argument("--project-name", help="Override manifest project.name")
    ap.add_argument("--variant", help="Override manifest project.variant")
    ap.add_argument("--source-os", help="Override manifest project.source_os")
    ap.add_argument("--target-os", help="Override manifest project.target_os")
    ap.add_argument("--clang", help="Override manifest tools.clang")
    ap.add_argument("--extractor-backend", choices=["auto", "ast-json", "libtooling"], help="Override manifest extraction.backend")
    ap.add_argument("--libtooling-extractor", help="Override manifest tools.libtooling_extractor")
    ap.add_argument("--libtooling-jobs", type=int, help="Override manifest extraction.libtooling_jobs")
    ap.add_argument("--kernel-build-dir", help="Override manifest inputs.kernel_build_dir")
    ap.add_argument("--include-generated-tu", action=argparse.BooleanOptionalAction, default=None)
    ap.add_argument("--clang-extra", action="append", default=None)
    ap.add_argument("--jobs", type=int, help="Override manifest extraction.ast_jobs")
    ap.add_argument("--strict", action=argparse.BooleanOptionalAction, default=None)
    ap.add_argument("--keep-ast", action=argparse.BooleanOptionalAction, default=None)
    ap.add_argument("--allow-source-scan", action=argparse.BooleanOptionalAction, default=None)
    ap.add_argument("--max-method-context-chars", type=int)
    ap.add_argument("--max-file-source-chars", type=int)
    args = ap.parse_args(argv)

    try:
        input_manifest_path = Path(args.manifest).expanduser().resolve()
        manifest = load_manifest(input_manifest_path, strict_env=True)
        manifest_errors = validate_manifest_basics(manifest)
        if manifest_errors:
            raise ManifestError("; ".join(manifest_errors))
        ignore_dirs, semantic_rules = apply_manifest_configuration(manifest)
    except (ManifestError, json.JSONDecodeError, OSError) as exc:
        eprint(f"ERROR: input manifest: {exc}")
        return 2

    def choose(cli: Any, dotted: str, default: Any = None) -> Any:
        return cli if cli is not None else get_path(manifest, dotted, default)

    source_ref = choose(args.source, "inputs.source_root")
    out_ref = choose(args.out, "output.root")
    if not source_ref or not out_ref:
        eprint("ERROR: manifest must define inputs.source_root and output.root (or provide CLI overrides)")
        return 2
    source = Path(str(source_ref)).expanduser()
    if not source.is_absolute(): source = (Path(manifest["_manifest"]["directory"]) / source).resolve()
    else: source = source.resolve()
    out = Path(str(out_ref)).expanduser()
    if not out.is_absolute(): out = (Path(manifest["_manifest"]["directory"]) / out).resolve()
    else: out = out.resolve()
    out.mkdir(parents=True, exist_ok=True)

    run_id = _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ") + f"-{os.getpid()}"
    run_terminal = {"done": False}
    write_run_state(out, run_id=run_id, status="RUNNING", phase="configuration",
                    message="Builder started; downstream artifacts are not valid until this run reaches COMPLETE.")
    import atexit as _atexit
    def _mark_incomplete_run() -> None:
        if not run_terminal["done"]:
            try:
                state_path = out / _workspace_rel("run_state_file", "manifest/run_state.json")
                current = json.loads(state_path.read_text(encoding="utf-8")) if state_path.is_file() else {}
                if current.get("run_id") == run_id and current.get("status") == "FAILED":
                    return
                write_run_state(out, run_id=run_id, status="FAILED", phase="aborted",
                                message="Builder exited before successful extraction completion. Existing downstream artifacts must not be treated as current.")
            except Exception:
                pass
    _atexit.register(_mark_incomplete_run)

    cc_ref = choose(args.compile_commands, "inputs.compile_commands")
    if cc_ref:
        cc = Path(str(cc_ref)).expanduser(); cc = cc if cc.is_absolute() else Path(manifest["_manifest"]["directory"]) / cc
        args.compile_commands = str(cc.resolve())
    else:
        args.compile_commands = None
    kb_ref = choose(args.kernel_build_dir, "inputs.kernel_build_dir")
    if kb_ref:
        kb = Path(str(kb_ref)).expanduser(); kb = kb if kb.is_absolute() else Path(manifest["_manifest"]["directory"]) / kb
        args.kernel_build_dir = str(kb.resolve())
    else:
        args.kernel_build_dir = None
    lt_ref = choose(args.libtooling_extractor, "tools.libtooling_extractor")
    if lt_ref:
        lt = Path(str(lt_ref)).expanduser(); lt = lt if lt.is_absolute() else Path(manifest["_manifest"]["directory"]) / lt
        args.libtooling_extractor = str(lt.resolve())
    else:
        args.libtooling_extractor = None

    required_manifest_values = {
        "project_name": choose(args.project_name, "project.name"),
        "variant": choose(args.variant, "project.variant"),
        "source_os": choose(args.source_os, "project.source_os"),
        "target_os": choose(args.target_os, "project.target_os"),
        "clang": choose(args.clang, "tools.clang"),
    }
    missing = [name for name, value in required_manifest_values.items() if value in (None, "")]
    if missing:
        eprint("ERROR: manifest/CLI is missing required value(s): " + ", ".join(missing))
        return 2
    args.project_name = str(required_manifest_values["project_name"])
    args.variant = str(required_manifest_values["variant"])
    args.source_os = str(required_manifest_values["source_os"])
    args.target_os = str(required_manifest_values["target_os"])
    args.clang = str(required_manifest_values["clang"])
    args.extractor_backend = str(choose(args.extractor_backend, "extraction.backend", "auto"))
    args.libtooling_jobs = int(choose(args.libtooling_jobs, "extraction.libtooling_jobs", 1))
    args.jobs = int(choose(args.jobs, "extraction.ast_jobs", max(1, min(4, os.cpu_count() or 1))))
    args.strict = bool(choose(args.strict, "extraction.strict", True))
    args.keep_ast = bool(choose(args.keep_ast, "extraction.keep_ast", False))
    args.allow_source_scan = bool(choose(args.allow_source_scan, "extraction.allow_source_scan", False))
    args.include_generated_tu = bool(choose(args.include_generated_tu, "extraction.include_generated_translation_units", False))
    args.clang_extra = list(choose(args.clang_extra, "extraction.clang_extra", []) or [])
    args.max_method_context_chars = int(choose(args.max_method_context_chars, "extraction.max_method_context_chars", 32000))
    args.max_file_source_chars = int(choose(args.max_file_source_chars, "extraction.max_file_source_chars", 70000))

    if not source.is_dir():
        eprint(f"ERROR: source directory not found: {source}")
        return 2
    libtooling_path = Path(args.libtooling_extractor).expanduser().resolve() if args.libtooling_extractor else None
    requested_backend = args.extractor_backend
    backend = requested_backend
    if backend == "auto":
        backend = "libtooling" if libtooling_path and libtooling_path.is_file() and os.access(libtooling_path, os.X_OK) else "ast-json"
    if backend == "libtooling":
        if not libtooling_path or not libtooling_path.is_file() or not os.access(libtooling_path, os.X_OK):
            eprint("ERROR: libtooling backend requires executable --libtooling-extractor")
            return 2
        if not args.compile_commands:
            eprint("ERROR: libtooling backend requires --compile-commands")
            return 2
    elif shutil.which(args.clang) is None and not Path(args.clang).exists():
        eprint(f"ERROR: clang not found: {args.clang}")
        return 2

    if args.compile_commands:
        cc_path = Path(args.compile_commands).expanduser().resolve()
        if not cc_path.is_file():
            eprint(f"ERROR: compile_commands.json not found: {cc_path}")
            return 2
        compile_units = load_compile_db(cc_path, source)
        authoritative = True
    else:
        if not args.allow_source_scan:
            eprint("ERROR: --compile-commands is required for authoritative analysis. Use --allow-source-scan only for a non-production fallback.")
            return 2
        compile_units = fallback_compile_units(source)
        authoritative = False

    if not compile_units:
        eprint("ERROR: no C/C++ translation units under source root were found in the compilation database")
        return 2

    excluded_generated: list[dict[str, Any]] = []
    if not args.include_generated_tu:
        kept: list[CompileUnit] = []
        for cu in compile_units:
            if is_kbuild_generated_tu(cu.file):
                excluded_generated.append({"file": cu.file, "reason": "generated Kbuild/module metadata TU"})
            else:
                kept.append(cu)
        compile_units = kept
        if excluded_generated:
            eprint(f"Excluded {len(excluded_generated)} generated Kbuild TU(s) (use --include-generated-tu to retain them).")
    if not compile_units:
        eprint("ERROR: no semantic driver translation units remain after generated-TU filtering")
        return 2

    authoritative_compile_units = list(compile_units)
    tooling_cc_path: Path | None = None
    tooling_diagnostics: list[dict[str, Any]] = []
    tooling_transformations: list[dict[str, Any]] = []
    kernel_build_dir: Path | None = None
    kernel_notes: list[str] = []
    if args.compile_commands:
        explicit_kbuild = Path(args.kernel_build_dir).expanduser().resolve() if args.kernel_build_dir else None
        kernel_build_dir, kernel_notes = infer_kernel_build_dir(compile_units, explicit_kbuild)
        for note in kernel_notes:
            eprint("Kbuild context: " + note)
        tooling_cc_path = out / "manifest" / "compile_commands.tooling.json"
        compile_units, tooling_diagnostics, tooling_transformations = write_tooling_compile_db(
            tooling_cc_path, compile_units, args.clang, kernel_build_dir
        )
        if tooling_diagnostics:
            for d in tooling_diagnostics[:4]:
                eprint("WARNING: " + d["messages"][0])
            if args.strict:
                eprint("ERROR: strict mode: Kbuild tooling context is incomplete. Pass --kernel-build-dir pointing at the prepared kernel objtree.")
                json_write(out / "manifest" / "tooling_context_errors.json", tooling_diagnostics)
                return 2

    metadata = {
        "tool": "nic_port_context_builder.py",
        "tool_version": TOOL_VERSION,
        "generated_utc": now_iso(),
        "project_name": args.project_name,
        "build_variant": args.variant,
        "source_os": args.source_os,
        "target_os": args.target_os,
        "source_root": str(source),
        "compile_database": norm(args.compile_commands) if args.compile_commands else None,
        "tooling_compile_database": str(tooling_cc_path) if tooling_cc_path else None,
        "kernel_build_dir": str(kernel_build_dir) if kernel_build_dir else None,
        "build_graph_authoritative": authoritative,
        "git_commit": run_git(source, "rev-parse", "HEAD"),
        "git_branch": run_git(source, "rev-parse", "--abbrev-ref", "HEAD"),
        "git_describe": run_git(source, "describe", "--always", "--dirty", "--tags"),
        "git_status_porcelain": run_git(source, "status", "--porcelain"),
        "translation_unit_count": len(compile_units),
        "extractor_backend": backend,
        "libtooling_extractor": str(libtooling_path) if libtooling_path else None,
    }
    json_write(out / "manifest" / "project.json", metadata)
    json_write(out / "manifest" / "compile_units.json", [asdict(x) for x in authoritative_compile_units])
    json_write(out / "manifest" / "tooling_compile_units.json", [asdict(x) for x in compile_units])
    json_write(out / "manifest" / "excluded_translation_units.json", excluded_generated)
